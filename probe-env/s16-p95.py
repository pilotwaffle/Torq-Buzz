# Parse paint log
paint = []
for line in PAINT_RAW.strip().split("\n"):
    m = re.search(r"epoch=(\d+) n=(\d+)", line)
    if m:
        paint.append((int(m.group(1)), int(m.group(2))))

# Parse emit clock
ANSI = re.compile(r"\x1b\[[0-9;]*m")
emit = []  # (seq, emit_ms)
with open(EMIT_LOG, "r", encoding="utf-8", errors="replace") as f:
    for line in f:
        line = ANSI.sub("", line)
        m = re.search(r"seq=(\d+).*emit_epoch_millis=(\d+)", line)
        if m:
            emit.append((int(m.group(1)), int(m.group(2))))

emit.sort(key=lambda x: x[1])
emit_ms_by_seq = {seq: ms for seq, ms in emit}

first_emit = emit[0][1]  # seq=1 emit ms
last_emit = emit[-1][1]

print("emit events:", len(emit), "seq range:", min(s for s,_ in emit), "-", max(s for s,_ in emit))
print("first_emit(seq1):", first_emit, " last_emit(seq1210):", last_emit)
print("paint entries:", len(paint), "n range:", min(n for _,n in paint), "-", max(n for _,n in paint))

# Determine pre-run5 offset P: first paint entry with epoch >= first_emit
first_run5_paint = None
for (ep, n) in paint:
    if ep >= first_emit:
        first_run5_paint = (ep, n)
        break
print("first run5-window paint entry:", first_run5_paint)

if first_run5_paint:
    ep0, n0 = first_run5_paint
    # how many emit events have emit_ms <= ep0?
    k = sum(1 for _, ms in emit if ms <= ep0)
    P = n0 - k
    print("events emitted by ep0:", k, "-> offset P =", P)

    # compute latency per paint entry: seq = n - P
    latencies = []
    for (ep, n) in paint:
        seq = n - P
        if seq in emit_ms_by_seq and ep >= first_emit:
            lat = ep - emit_ms_by_seq[seq]
            if 0 <= lat < 10000:
                latencies.append(lat)

    latencies.sort()
    def pct(p):
        if not latencies:
            return None
        idx = min(len(latencies) - 1, int(round(p * (len(latencies) - 1))))
        return latencies[idx]

    print("\nlatency samples (n>offset, epoch>=first_emit):", len(latencies))
    print("min:", latencies[0] if latencies else None)
    print("p50:", pct(0.50))
    print("p90:", pct(0.90))
    print("p95:", pct(0.95))
    print("p99:", pct(0.99))
    print("max:", latencies[-1] if latencies else None)
    print("\nfirst 20 latencies:", latencies[:20])
